			CALL RUNSONG4
		VOICE4SKIP:
		
	CHECKNOTE5TIMER:
	DEC NOTETIMERS5
	BNE VOICE5SKIP
		PLAYSONG5:	;PLAY NEXT NOTE
			MOV A, EFFECT5ON
			BEQ VOICE5SKIP
			CALL RUNSONG5
		VOICE5SKIP:
		
	CHECKNOTE6TIMER:
	DEC NOTETIMERS6
	BNE VOICE6SKIP
		PLAYSONG6:	;PLAY NEXT NOTE
			MOV A, EFFECT6ON
			BEQ VOICE6SKIP
			CALL RUNSONG6
		VOICE6SKIP:
		
	CHECKNOTE7TIMER:
	DEC NOTETIMERS7
	BNE VOICE7SKIP
		PLAYSONG7:	;PLAY NEXT NOTE
			MOV A, EFFECT7ON
			BEQ VOICE7SKIP
			CALL RUNSONG7
		VOICE7SKIP:
	
	;CHECK IF NEED TO RESTART SONG
	MOV A, RESETCURRENTSONG
	BNE SKIPVOICES
		MOV A, #$56
		MOV A, CURRENTSONG
		BNE RESETOTHERSONG	
			CALL RESETSONG0
			BRA SKIPVOICES
		RESETOTHERSONG:
			CALL RESETSONG1
	
	SKIPVOICES:
	;CHECK FOR SOUND EFFECTS ON APU DATA LINES
	;[
	MOV A, CPUIO0
	CMP A, LASTEFFECTVAL
	BNE EFFECTEVENT
	JMP NOEFFECTEVENT	;NO NEW DATA INCOMING
		EFFECTEVENT:
		;WRITE ACKNOWLEDGE
		MOV CPUIO0, A
		MOV LASTEFFECTVAL, A
		;READ EFFECT SOUND AND CHANNEL
		MOV A, CPUIO1	;READ FROM CPU
		CMP A, #$FF		;SIGNAL TO START NEW SONG
		BEQ STARTSONG1
		ASL A
		BCS SETEFFECT5
		ASL A
		BCS SETEFFECT6
		ASL A
		BCS SETEFFECT7
		JMP NOEFFECTEVENT
	
		STARTSONG1:
			MOV DSPADDR, #KOFF	;MUTE ALL K VOICES
			MOV DSPDATA, #$FF	
			MOV A, #$01
			MOV CURRENTSONG, A
			CALL RESETSONG1
			JMP NOEFFECTEVENT
	
		SETEFFECT5:
			;SET INDEX OF EFFECT
			MOV A, CPUIO1
			AND A, #$1F
			ASL A
			ASL A	;FOUR BYTE SHIFT
			MOV X, A
			MOV A, SOUNDEFFECTTABLE+1+X
			MOV Y, A
			MOV A, SOUNDEFFECTTABLE+X
			MOVW EFFECTPOINTER5, YA
			;SET LENGTH OF EFFECT
			MOV A, SOUNDEFFECTTABLE+2+X
			MOV LENS5, A
			;START EFFECT
			INC EFFECT5ON
			MOV NOTETIMERS5, #$01
			MOV A, #$00
			MOV COUNTERS5, A
			MOV COUNTERS5+1, A
			;TURN CHANNEL BACK ON
			MOV DSPADDR, #KOFF
			MOV A, DSPDATA
			AND A, #$DF
			MOV DSPDATA, A		;ENABLE VOICE 5
			BRA NOEFFECTEVENT
		SETEFFECT6:
			;SET INDEX OF EFFECT
			MOV A, CPUIO1
			AND A, #$1F
			ASL A
			ASL A	;FOUR BYTE SHIFT
			MOV X, A
			MOV A, SOUNDEFFECTTABLE+1+X
			MOV Y, A
			MOV A, SOUNDEFFECTTABLE+X
			MOVW EFFECTPOINTER6, YA
			;SET LENGTH OF EFFECT
			MOV A, SOUNDEFFECTTABLE+2+X
			MOV LENS6, A
			;START EFFECT
			INC EFFECT6ON
			MOV NOTETIMERS6, #$01
			MOV A, #$00
			MOV COUNTERS6, A
			MOV COUNTERS6+1, A
			;TURN CHANNEL BACK ON
			MOV DSPADDR, #KOFF
			MOV A, DSPDATA
			AND A, #$BF
			MOV DSPDATA, A		;ENABLE VOICE 6
			BRA NOEFFECTEVENT
		SETEFFECT7:
			;SET INDEX OF EFFECT
			MOV A, CPUIO1
			AND A, #$1F
			ASL A
			ASL A	;FOUR BYTE SHIFT
			MOV X, A
			MOV A, SOUNDEFFECTTABLE+1+X
			MOV Y, A
			MOV A, SOUNDEFFECTTABLE+X
			MOVW EFFECTPOINTER7, YA
			;SET LENGTH OF EFFECT
			MOV A, SOUNDEFFECTTABLE+2+X
			MOV LENS7, A
			;START EFFECT
			INC EFFECT7ON
			MOV NOTETIMERS7, #$01
			MOV A, #$00
			MOV COUNTERS7, A
			MOV COUNTERS7+1, A
			;TURN CHANNEL BACK ON
			MOV DSPADDR, #KOFF
			MOV A, DSPDATA
			AND A, #$7F
			MOV DSPDATA, A		;ENABLE VOICE 7
	;]
	NOEFFECTEVENT:
		
	JMP RUNMUSICENGINE		  ;MAIN AUDIO EXECUTIONLOOP
;]

RUNSONG0:
;[
	MOV A, COUNTERS0+1
	CMP A, LENS0+1
	BNE SETNOTE0
	COMPARELOWERS0:
	MOV A, COUNTERS0
	CMP A, LENS0
	BCS CHECKTURNOFFSONG0
	
	SETNOTE0:
	;SET PITCH FOR VOICE0
	;$1000 IS STANDARD PLAYBACK SPEED (APPROX 32KHZ DEPENDING ON SAMPLE RATE)
	MOV Y, #$00
	MOV A, (SONGPOINTER0)+Y
	MOV DSPADDR, #(VXPITCHL | VOICE0)
	MOV DSPDATA, A
	INC Y
	MOV A, (SONGPOINTER0)+Y
	MOV DSPADDR, #(VXPITCHH | VOICE0)
	MOV DSPDATA, A

	;SET VOLUME FOR VOICE0
	INC Y
	MOV A, (SONGPOINTER0)+Y
	AND A, MAXVOL0
	MOV DSPADDR, #(VXVOLL | VOICE0)
	MOV DSPDATA, A
	MOV DSPADDR, #(VXVOLR | VOICE0)
	MOV DSPDATA, A

	;SET VOLUME ENVELOPE (GAIN) FOR VOICE0
	;DIRECT GAIN MODE, MAX VOLUME
	INC Y
	MOV A, (SONGPOINTER0)+Y
	MOV DSPADDR, #(VXGAIN | VOICE0)
	MOV DSPDATA, A
	
	;SET CURRENT NOTE DURATION TIMER
	INC Y
	MOV A, (SONGPOINTER0)+Y
	MOV NOTETIMERS0, A
	INC Y
	MOV A, (SONGPOINTER0)+Y
	MOV NOTETIMERS0+1, A
	
	;SET INSTRUMENT
	INC Y
	MOV A, (SONGPOINTER0)+Y
	;CONFIGURE VOICE0 TO USE SAMPLE #0
	MOV DSPADDR, #(VXSRCN | VOICE0)
	MOV DSPDATA, A
	
	;INCREASE INDEX FOR NEXT NOTE
	INC COUNTERS0
	BNE NOC0
		INC COUNTERS0+1
	NOC0:
	
	MOVW YA, SONGPOINTER0
	CLRC
	ADC A, #07
	MOV SONGPOINTER0, A
	MOV A, Y
	ADC A, #00
	MOV SONGPOINTER0+1, A
	
	;KEY ON - TRIGGER VOICE 0
	MOV DSPADDR, #KON
	MOV DSPDATA, #$01		;SET BIT TO TRIGGER VOICE 0
		
	BRA ENDRUNSONG0

	CHECKTURNOFFSONG0:
		MOV A, #$01
		MOV DSPDATA, #$01		;CLEAR VOICE 0
		
		MOV A, REPEATS0
		CMP A, #$00
		BEQ TURNOFFS0
			;TRACK 0 WHEN DONE, MARK FOR REPEAT
			DEC RESETCURRENTSONG
			;BRA ENDRUNSONG0
		TURNOFFS0:
			MOV A, #$01
			MOV SONGOVERS0, A		;MARK SONG AS OVER
	ENDRUNSONG0:
	RET
;]

