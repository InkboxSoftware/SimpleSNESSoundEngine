	MOV DSPDATA, #$00
	
	;RESET COUNTER
	MOV A, REPEATS0
	CLRC
	ADC A, REPEATS1
	ADC A, REPEATS2
	ADC A, REPEATS3
	ADC A, REPEATS4
	MOV RESETCURRENTSONG, A
	
	RET
;]

