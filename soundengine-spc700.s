;SPC-700 SOUND ENGINE

; Undocumented register, should not be touched.
TEST = $00F0
CONTROL = $00F1
; DSP register numbers are defined further down.
DSPADDR = $00F2
DSPDATA = $00F3
; CPU communication ports, equivalent to $2140 - $2143.
CPUIO0 = $00F4
CPUIO1 = $00F5
CPUIO2 = $00F6
CPUIO3 = $00F7
; Aux ports are unconnected but function like general-purpose RAM.
; S-SMP pins 34-27.
AUXIO4 = $00F8
; S-SMP pins 25-18.
AUXIO5 = $00F9
T0DIV = $00FA
T1DIV = $00FB
T2DIV = $00FC
T0OUT = $00FD
T1OUT = $00FE
T2OUT = $00FF

;;; DSP Registers.
;;; These are 8-bit register addresses written to DSPADDR.
;;; $80-$FF are read-only mirrors of $00-$7F.
; Voice-specific registers, should be offset with the voice offset constants below.
VXVOLL = $0
VXVOLR = $1
VXPITCHL = $2
VXPITCHH = $3
VXSRCN = $4
VXADSR1 = $5
VXADSR2 = $6
VXGAIN = $7
VXENVX = $8
VXOUTX = $9
FIRX = $F
; Unused registers; can be used for 8 bytes of general-purpose RAM each.
NAxA = $A
NAxB = $B
NAxE = $E

; Voice offsets; add to registers containing "x" to get the register specific to a voice.
VOICE0 = $00
VOICE1 = $10
VOICE2 = $20
VOICE3 = $30
VOICE4 = $40
VOICE5 = $50
VOICE6 = $60
VOICE7 = $70

; Global DSP registers.
MVOLL = $0C
MVOLR = $1C
EVOLL = $2C
EVOLR = $3C
KON = $4C
KOFF = $5C
FLG = $6C
ENDX = $7C
EFB = $0D
PMON = $2D
NON = $3D
EON = $4D
DIR = $5D
ESA = $6D
EDL = $7D
; Unused register, can be used for general-purpose RAM.
NA_1D = $1D

ORG $0040
SONGPOINTER0: BYTE $00, $00
SONGPOINTER1: BYTE $00, $00
SONGPOINTER2: BYTE $00, $00
SONGPOINTER3: BYTE $00, $00
SONGPOINTER4: BYTE $00, $00

EFFECTPOINTER5: BYTE $00, $00
EFFECTPOINTER6: BYTE $00, $00
EFFECTPOINTER7: BYTE $00, $00

NOTETIMERS0: WORD $0000
NOTETIMERS1: WORD $0000
NOTETIMERS2: WORD $0000
NOTETIMERS3: WORD $0000
NOTETIMERS4: WORD $0000
NOTETIMERS5: WORD $0000
NOTETIMERS6: WORD $0000
NOTETIMERS7: WORD $0000

LASTEFFECTVAL: BYTE $00
EFFECT5ON: BYTE $00	;0 FOR OFF
EFFECT6ON: BYTE $00	;0 FOR OFF
EFFECT7ON: BYTE $00	;0 FOR OFF


CURRENTSONG:BYTE $00
RESETCURRENTSONG: BYTE $00

TMPA: BYTE $00, $00

ORG $0200			  ;CODE STARTS AT $0200
startpos
MAIN:
	CLRC	;CLEAR CARRY
	DI		;DISABLE INTERRUPTS
	CLRP	;CLEAR PAGE

	;ENABLE IPL
	MOV CONTROL, #$CF

	;RESET SOUND
	MOV A, #FLG
	MOV Y, #$FF	;RESET + MUTE ALL VOICES
	MOVW DSPADDR, YA
	INC Y
	MOV A, #(FIRX | VOICE7)

	;INIT ALL DSP REGISTERS
MAININITLOOP:
	MOVW DSPADDR, YA
	MOV Y, #$00
	CMP A, #(FLG + 1)
	BNE MAININITLOOP_NOT_FLG
	MOV Y, #$29	;NOISE FREQUENCY + ECHO DISABLE

MAININITLOOP_NOT_FLG:
	CMP A, #(ESA + 1)
	BNE MAININITLOOP_NOT_ESA
	MOV Y, #$88	;SET ESA TO POINT TO $8800

MAININITLOOP_NOT_ESA:
	DEC A
	BPL MAININITLOOP
	
	;SET TIMER 0 RESTART AT 128HZ
	MOV T0DIV, #$32
	
	;CLEAR VARIABLES
		MOV A, #$20	;SMALL TIME BUFFER
		MOV NOTETIMERS0, A
		MOV NOTETIMERS1, A
		MOV NOTETIMERS2, A
		MOV NOTETIMERS3, A
		MOV NOTETIMERS4, A
		MOV EFFECT5ON, Y
		MOV EFFECT6ON, Y
		MOV EFFECT7ON, Y
		MOV LASTEFFECTVAL, Y
	
	;SET MAIN VOLUME TO MAX
	MOV A, #MVOLL
	MOV Y, #$7F
	MOVW DSPADDR, YA		;MAX LEFT VOLUME	(SIGNED)
	MOV A, #MVOLR
	MOVW DSPDATA, YA		;MAX RIGHT VOLUME

	;POINT DSP TO THE SAMPLE DIRECTORY (DIR)
	;SET DIR REGISTER TO VALUE OF DIRTABLE
	MOV DSPADDR, #DIR
	MOV DSPDATA, #DIRTABLE		;HIGH 8-BITS OF 16-BIT ADDRESS
	
	CALL RESETSONG0
	
	;RESET APU DATA PORTS
	MOV A, #$00
	MOV Y, A
	MOVW CPUIO0, YA
	MOVW CPUIO2, YA

RUNMUSICENGINE:	
;[
	;CHECK TIMER (READ IS DESTRUCTIVE, RESETS TO 0, SO I CAN ONLY CHECK IF NONZERO)
	MOV A, T0OUT
	BNE CHECKNOTE0TIMER
	JMP SKIPVOICES

	CHECKNOTE0TIMER:
	MOV A, NOTETIMERS0
	OR A, NOTETIMERS0+1
	BEQ PLAYSONG0
	MOV A, NOTETIMERS0
	BNE DECNT0
	DEC NOTETIMERS0+1
	DECNT0:
	DEC NOTETIMERS0
	MOV A, NOTETIMERS0
	OR A, NOTETIMERS0+1
	BNE VOICE0SKIP
		PLAYSONG0:	;PLAY NEXT NOTE
			MOV A, SONGOVERS0
			BNE VOICE0SKIP
			CALL RUNSONG0
		VOICE0SKIP:
	
	CHECKNOTE1TIMER:
	MOV A, NOTETIMERS1
	OR A, NOTETIMERS1+1
	BEQ PLAYSONG1
	MOV A, NOTETIMERS1
	BNE DECNT1
	DEC NOTETIMERS1+1
	DECNT1:
	DEC NOTETIMERS1
	MOV A, NOTETIMERS1
	OR A, NOTETIMERS1+1
	BNE VOICE1SKIP
		PLAYSONG1:	;PLAY NEXT NOTE
			MOV A, SONGOVERS1
			BNE VOICE1SKIP
			CALL RUNSONG1
		VOICE1SKIP:
	
	CHECKNOTE2TIMER:
	MOV A, NOTETIMERS2
	OR A, NOTETIMERS2+1
	BEQ PLAYSONG2
	MOV A, NOTETIMERS2
	BNE DECNT2
	DEC NOTETIMERS2+1
	DECNT2:
	DEC NOTETIMERS2
	MOV A, NOTETIMERS2
	OR A, NOTETIMERS2+1
	BNE VOICE2SKIP
		PLAYSONG2:	;PLAY NEXT NOTE
			MOV A, SONGOVERS2
			BNE VOICE2SKIP
			CALL RUNSONG2
		VOICE2SKIP:
	
	CHECKNOTE3TIMER:
	MOV A, NOTETIMERS3
	OR A, NOTETIMERS3+1
	BEQ PLAYSONG3
	MOV A, NOTETIMERS3
	BNE DECNT3
	DEC NOTETIMERS3+1
	DECNT3:
	DEC NOTETIMERS3
	MOV A, NOTETIMERS3
	OR A, NOTETIMERS3+1
	BNE VOICE3SKIP
		PLAYSONG3:	;PLAY NEXT NOTE
			MOV A, SONGOVERS3
			BNE VOICE3SKIP
			CALL RUNSONG3
		VOICE3SKIP:
		
	CHECKNOTE4TIMER:
