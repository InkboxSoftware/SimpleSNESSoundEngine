	BNE NOC4
		INC COUNTERS4+1
	NOC4:
	
	MOVW YA, SONGPOINTER4
	CLRC
	ADC A, #07
	MOV SONGPOINTER4, A
	MOV A, Y
	ADC A, #00
	MOV SONGPOINTER4+1, A
	
