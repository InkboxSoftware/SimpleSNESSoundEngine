SHAREDRESTARTLOGIC:
;[
	;RESET TIMERS
	MOV A, #$80	;SMALL TIME BUFFER
	MOV NOTETIMERS0, A
	MOV NOTETIMERS1, A
	MOV NOTETIMERS2, A
	MOV NOTETIMERS3, A
	MOV NOTETIMERS4, A
	;RESET TRACKERS
	MOV A, #$00
	MOV COUNTERS0, A
	MOV COUNTERS0+1, A
	MOV COUNTERS1, A
	MOV COUNTERS1+1, A
	MOV COUNTERS2, A
	MOV COUNTERS2+1, A
	MOV COUNTERS3, A
	MOV COUNTERS3+1, A
	MOV COUNTERS4, A
	MOV COUNTERS4+1, A
		MOV SONGOVERS0, A		;MARK SONG AS NOT OVER
